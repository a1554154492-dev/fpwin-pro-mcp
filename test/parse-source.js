#!/usr/bin/env node
'use strict';
/**
 * parse-source.js - validate reconstructed POU source text against .asc exports.
 *
 * For every .pro/.asc pair: parse the POU body out of the .pro (zlib + UTF-16LE
 * content chunks of the POU's text section) and compare it with the BODY…END_BODY
 * block of the matching object in the .asc export.
 *
 * usage: node test/parse-source.js <dirWithPairs> [--diff]
 */
const fs = require('fs');
const path = require('path');
const { parseProject, extractContents, pous, pouSource } = require('../lib/proparse');

const DECL_RE = /^(PROGRAM|FUNCTION_BLOCK|FUNCTION)\s+([A-Za-z_\u00c0-\uffff][\w\u00c0-\uffff]*)/;

function ascBodies(text) {
  const bodies = new Map();
  const lines = text.split(/\r?\n/);
  let current = null;
  let inBody = false;
  let buf = [];
  for (const line of lines) {
    const m = DECL_RE.exec(line.trim());
    if (m && !inBody) { current = m[2]; continue; }
    if (line.trim() === 'BODY' && current) { inBody = true; buf = []; continue; }
    if (inBody) {
      if (line.trim() === 'END_BODY') { bodies.set(current, buf.join('\n')); inBody = false; current = null; continue; }
      buf.push(line);
    }
  }
  return bodies;
}

function norm(s) {
  return s
    .replace(/\r\n/g, '\n')
    .replace(/^\s*END_BODY\s*$/gm, '')
    .replace(/\?[A-Za-z_@][A-Za-z0-9_@']*/g, '') // pin parameter lists are regenerated by the exporter
    .replace(/[^\x20-\x7e\n\t]/g, '?') // .asc uses U+FFFD placeholders where .pro keeps the real glyph
    .split('\n').map((l) => l.replace(/[ \t]+$/, '')).join('\n').trim();
}

/**
 * The .asc export and the stored body are not byte-identical: the exporter
 * regenerates some graphical connection lines (L(...)) and pin parameter lists.
 * Compare the structural content instead: the identifier set and the network
 * count must match.
 */
function shape(text) {
  const identifiers = new Set();
  for (const m of text.matchAll(/[A-Za-z_@][A-Za-z0-9_.@:]{1,}/g)) identifiers.add(m[0]);
  const networks = (text.match(/NET_WORK\b/g) || []).length;
  const elements = (text.match(/^B\(/gm) || []).length;
  return { identifiers, networks, elements };
}

function jaccard(a, b) {
  let inter = 0;
  for (const x of a) if (b.has(x)) inter++;
  const union = a.size + b.size - inter;
  return union === 0 ? 1 : inter / union;
}

const dir = process.argv[2];
const showDiff = process.argv.includes('--diff');
if (!dir) { console.error('usage: parse-source.js <dir> [--diff]'); process.exit(2); }

let projects = 0, matched = 0, structural = 0, mismatched = 0, missing = 0, noBody = 0;
const diffs = [];
for (const f of fs.readdirSync(dir).filter((x) => x.toLowerCase().endsWith('.pro'))) {
  const proPath = path.join(dir, f);
  const ascPath = proPath.replace(/\.pro$/i, '.asc');
  if (!fs.existsSync(ascPath)) continue;
  projects++;
  const buf = fs.readFileSync(proPath);
  const project = parseProject(buf, { file: proPath });
  const contents = extractContents(buf, project);
  const declared = ascBodies(fs.readFileSync(ascPath, 'utf8'));
  for (const pou of pous(project)) {
    const expected = declared.get(pou.name);
    if (expected === undefined) { missing++; continue; }
    const src = pouSource(project, contents, pou);
    if (!src.text) { noBody++; continue; }
    // .pro body text starts with "BODY" line; the asc body we captured excludes it
    const gotRaw = norm(src.text.replace(/^BODY\s*\r?\n?/, ''));
    const wantRaw = norm(expected);
    const got = shape(gotRaw);
    const want = shape(wantRaw);
    const sim = jaccard(got.identifiers, want.identifiers);
    if (gotRaw === wantRaw) { matched++; continue; }
    if (sim >= 0.98 && got.networks === want.networks) { matched++; structural++; continue; }
    mismatched++;
    if (diffs.length < 4) {
      diffs.push({
        file: f, pou: pou.name, similarity: sim.toFixed(3),
        networks: got.networks + '/' + want.networks, elements: got.elements + '/' + want.elements,
        onlyGot: [...got.identifiers].filter((x) => !want.identifiers.has(x)).slice(0, 6),
        onlyWant: [...want.identifiers].filter((x) => !got.identifiers.has(x)).slice(0, 6),
      });
    }
  }
}
console.log('projects=' + projects + ' matched=' + matched + ' (structural=' + structural + ')' +
  ' mismatched=' + mismatched + ' ascWithoutBody=' + missing + ' noProBody=' + noBody);
if (showDiff) for (const d of diffs) console.log('DIFF ' + d.file + ' :: ' + d.pou + ' sim=' + d.similarity + ' networks=' + d.networks + ' elements=' + d.elements +
  '\n  onlyGot : ' + JSON.stringify(d.onlyGot) + '\n  onlyWant: ' + JSON.stringify(d.onlyWant));
if (mismatched > 0 || (matched === 0 && projects > 0)) process.exitCode = 1;
